class GradientReversalFunction(Function):
    """
    Gradient Reversal Layer (GRL)
    Forward pass: identity function
    Backward pass: reverses and scales gradient

    This is the KEY component for fairness - it makes the encoder learn
    representations that cannot predict protected attributes
    """

    @staticmethod
    def forward(ctx, x, lambda_):
        ctx.lambda_ = lambda_
        return x.view_as(x)

    @staticmethod
    def backward(ctx, grad_output):
        return grad_output.neg() * ctx.lambda_, None

class GradientReversalLayer(nn.Module):
    def __init__(self, lambda_=1.0):
        super(GradientReversalLayer, self).__init__()
        self.lambda_ = lambda_

    def forward(self, x):
        return GradientReversalFunction.apply(x, self.lambda_)

class FairnessAwareFloodModel(nn.Module):
    """
    Fairness-Aware Model for Flood Vulnerability Prediction

    Architecture:
    1. Encoder: Learns vulnerability representations from input features
    2. Task Predictor: Predicts economic damage (main task)
    3. Adversarial Predictor: Tries to predict district from representations
    4. GRL: Forces encoder to create district-invariant representations

    Loss: L = L_task - ̵ * L_adversarial
    """

    def __init__(self, input_dim, hidden_dim=128, n_protected_classes=9, lambda_adv=1.0):
        super(FairnessAwareFloodModel, self).__init__()

        # Encoder: Learns bias-invariant representations
        self.encoder = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.BatchNorm1d(hidden_dim // 2),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(hidden_dim // 2, 32)
        )

        # Task predictor: Damage prediction
        self.task_head = nn.Sequential(
            nn.Linear(32, 16),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(16, 1)
        )

        # Adversarial predictor: District classification (to be confused)
        self.gradient_reversal = GradientReversalLayer(lambda_=lambda_adv)
        self.adversarial_head = nn.Sequential(
            nn.Linear(32, 16),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(16, n_protected_classes)
        )

    def forward(self, x):
        # Encode input features
        encoded = self.encoder(x)

        # Task prediction (damage)
        damage_pred = self.task_head(encoded)

        # Adversarial prediction (district) - with gradient reversal
        reversed_encoded = self.gradient_reversal(encoded)
        protected_pred = self.adversarial_head(reversed_encoded)

        return damage_pred, protected_pred

