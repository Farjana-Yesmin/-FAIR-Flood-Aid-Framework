def train_fair_model(model, train_loader, optimizer, task_criterion, adv_criterion, device):
    """Train fairness-aware model for one epoch"""
    model.train()
    total_task_loss = 0
    total_adv_loss = 0
    total_loss = 0

    for X_batch, y_batch, protected_batch in train_loader:
        X_batch = X_batch.to(device)
        y_batch = y_batch.to(device)
        protected_batch = protected_batch.to(device)

        optimizer.zero_grad()

        # Forward pass
        damage_pred, protected_pred = model(X_batch)

        # Calculate losses
        task_loss = task_criterion(damage_pred.squeeze(), y_batch)
        adv_loss = adv_criterion(protected_pred, protected_batch)

        # Combined loss: maximize task accuracy, minimize adversarial accuracy
        loss = task_loss - lambda_adv * adv_loss

        # Backward pass
        loss.backward()
        optimizer.step()

        total_task_loss += task_loss.item()
        total_adv_loss += adv_loss.item()
        total_loss += loss.item()

    return (total_task_loss / len(train_loader),
            total_adv_loss / len(train_loader),
            total_loss / len(train_loader))

def train_baseline_model(model, train_loader, optimizer, criterion, device):
    """Train baseline model for one epoch"""
    model.train()
    total_loss = 0

    for X_batch, y_batch, _ in train_loader:
        X_batch = X_batch.to(device)
        y_batch = y_batch.to(device)

        optimizer.zero_grad()
        pred = model(X_batch)
        loss = criterion(pred.squeeze(), y_batch)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

    return total_loss / len(train_loader)

def evaluate_model(model, data_loader, device, is_fair_model=True):
    """Evaluate model"""
    model.eval()
    all_preds = []
    all_targets = []
    all_protected = []

    with torch.no_grad():
        for X_batch, y_batch, protected_batch in data_loader:
            X_batch = X_batch.to(device)

            if is_fair_model:
                damage_pred, _ = model(X_batch)
            else:
                damage_pred = model(X_batch)

            all_preds.extend(damage_pred.squeeze().cpu().numpy())
            all_targets.extend(y_batch.numpy())
            all_protected.extend(protected_batch.numpy())

    return np.array(all_preds), np.array(all_targets), np.array(all_protected)


